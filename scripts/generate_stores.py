def build():
    cities_obj = {}
    city_center_obj = {}
    aliases_obj = {}

    # 城市 ID 前缀（2 字符，好认）
    CITY_ID_PREFIX = {
        "北京": "BJ", "上海": "SH", "天津": "TJ", "重庆": "CQ",
        "石家庄": "SJZ", "太原": "TY", "呼和浩特": "HH", "沈阳": "SY",
        "长春": "CC", "哈尔滨": "HEB", "南京": "NJ", "杭州": "HZ",
        "合肥": "HF", "福州": "FZ", "南昌": "NC", "济南": "JN",
        "郑州": "ZZ", "武汉": "WH", "长沙": "CS", "广州": "GZ",
        "南宁": "NN", "海口": "HK", "成都": "CD", "贵阳": "GY",
        "昆明": "KM", "拉萨": "LS", "西安": "XA", "兰州": "LZ",
        "西宁": "XN", "银川": "YC", "乌鲁木齐": "WLMQ",
        "深圳": "SZ", "苏州": "SU", "青岛": "QD", "大连": "DL",
        "宁波": "NB", "厦门": "XM", "无锡": "WX", "佛山": "FS",
        "东莞": "DG", "温州": "WZ",
    }

    for city, lat, lng, aliases in CITIES:
        # cityCenter
        city_center_obj[city] = {"lat": lat, "lng": lng}

        # aliases
        for a in aliases:
            if a and a not in aliases_obj:
                aliases_obj[a] = city

        # stores
        city_stores = STORES.get(city, [])
        prefix = CITY_ID_PREFIX.get(city, city.encode("utf-8").hex()[:4].upper())
        stores = []
        for i, (name, addr, slat, slng) in enumerate(city_stores, start=1):
            sid = f"{prefix}{i:03d}"
            stores.append({
                "id": sid,
                "name": name,
                "address": f"{city}市{addr}",
                "lat": slat,
                "lng": slng,
            })
        cities_obj[city] = stores

    out = {
        "_comment": "全国麦当劳虚拟门店数据：4 直辖市 + 27 省会/首府 + 10 主要城市，共 41 城、约 100 家门店。支持城市名 + 城市别名（如'帝都'→北京、'魔都'→上海、'羊城'→广州）。",
        "cities": cities_obj,
        "cityCenter": city_center_obj,
        "cityAliases": aliases_obj,
    }
    return out


def main():
    data = build()
    out_path = Path(__file__).parent.parent / "source" / "data" / "stores.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    # 摘要
    total_cities = len(data["cities"])
    total_stores = sum(len(v) for v in data["cities"].values())
    total_aliases = len(data["cityAliases"])
    print(f"已生成 {out_path}")
    print(f"  城市数：{total_cities}")
    print(f"  门店数：{total_stores}")
    print(f"  别名数：{total_aliases}")


if __name__ == "__main__":
    main()
